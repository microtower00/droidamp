package com.droidamp.player.interop

import com.droidamp.player.domain.contract.AutoEqRule
import com.droidamp.player.domain.model.EqPreset
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.ByteArrayOutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

class DroidAmpFileSnifferTest {
  private val eqfCodec = BinaryEqfCodec()
  private val q2Codec = WinampQ2Codec()

  @Test
  fun sniffsLegacyAndAugmentedWszSkins() {
    val legacyZip =
      buildZip(
        "MySkin/Main.BMP" to byteArrayOf(0x42, 0x4D, 1, 2),
        "MySkin/viscolor.txt" to "0,0,0\r\n".toByteArray(Charsets.US_ASCII),
        "MySkin/pledit.txt" to "[Text]\r\nNormal=#00FF00\r\n".toByteArray(Charsets.US_ASCII),
      )
    val legacyDetected = DroidAmpFileSniffer.sniff(legacyZip, "Microchip_2.wsz")
    assertTrue(legacyDetected is DetectedWinampFormat.WszSkin)
    legacyDetected as DetectedWinampFormat.WszSkin
    assertFalse(legacyDetected.isAugmented)
    assertEquals(3, legacyDetected.entryCount)

    val augmentedZip =
      buildZip(
        "droidamp.json" to """{"schemaVersion":1,"name":"Cyber Ice"}""".toByteArray(Charsets.UTF_8),
        "sprites/header_deck.png" to byteArrayOf(0x89.toByte(), 0x50, 0x4E, 0x47),
      )
    val augmentedDetected = DroidAmpFileSniffer.sniff(augmentedZip, "cyber_ice.wsz")
    assertTrue(augmentedDetected is DetectedWinampFormat.WszSkin)
    augmentedDetected as DetectedWinampFormat.WszSkin
    assertTrue(augmentedDetected.isAugmented)
    assertEquals(2, augmentedDetected.entryCount)
  }

  @Test
  fun sniffsEqfQ1AndQ2BinaryFormats() {
    val rockPreset =
      EqPreset(
        name = "Rock",
        preampDb = 0f,
        bandsDb = listOf(4f, 3f, -2f, -3f, -1f, 2f, 4f, 5f, 5f, 5f),
      )
    val technoPreset =
      EqPreset(
        name = "Techno",
        preampDb = 1f,
        bandsDb = listOf(5f, 4f, 0f, -3f, -2f, 0f, 4f, 5f, 5f, 4f),
      )

    val eqfBytes = eqfCodec.encodeSingleEqf(rockPreset)
    assertEquals(DetectedWinampFormat.EqfSinglePreset, DroidAmpFileSniffer.sniff(eqfBytes, "rock.eqf"))
    assertEquals(DetectedWinampFormat.EqfSinglePreset, DroidAmpFileSniffer.sniff(eqfBytes, "wrong_ext.wsz"))

    val q1Bytes = eqfCodec.encodePresetLibraryQ1(listOf(rockPreset, technoPreset))
    assertEquals(DetectedWinampFormat.EqLibraryQ1, DroidAmpFileSniffer.sniff(q1Bytes, "winamp.q1"))
    assertEquals(DetectedWinampFormat.EqLibraryQ1, DroidAmpFileSniffer.sniff(q1Bytes, null))

    val q2Bytes =
      q2Codec.encodeAutoPresetsQ2(
        listOf(
          AutoEqRule(pattern = "*/The Doors/*.mp3", preset = rockPreset),
          AutoEqRule(pattern = "*.flac", preset = technoPreset),
        ),
      )
    assertEquals(DetectedWinampFormat.AutoEqQ2, DroidAmpFileSniffer.sniff(q2Bytes, "winamp.q2"))
    assertEquals(DetectedWinampFormat.AutoEqQ2, DroidAmpFileSniffer.sniff(q2Bytes, "renamed_rules.bin"))
  }

  @Test
  fun sniffsWinampIniM3u8AndPlsTextFormats() {
    val iniBytes =
      "; Generated by Winamp 2.91\r\n[Winamp]\r\nvolume=200\r\neq_ws=1\r\n".toByteArray(Charsets.UTF_8)
    assertEquals(DetectedWinampFormat.WinampIni, DroidAmpFileSniffer.sniff(iniBytes, "winamp.ini"))

    val m3u8Bytes =
      "\uFEFF#EXTM3U\n#EXTINF:471,The Doors - L.A. Woman\nRock/LA_Woman.mp3\n".toByteArray(Charsets.UTF_8)
    assertEquals(DetectedWinampFormat.PlaylistM3u, DroidAmpFileSniffer.sniff(m3u8Bytes, "favorites.m3u8"))

    val plainM3uBytes = "Albums/Track01.flac\nAlbums/Track02.flac\n".toByteArray(Charsets.UTF_8)
    assertEquals(DetectedWinampFormat.PlaylistM3u, DroidAmpFileSniffer.sniff(plainM3uBytes, "mix.m3u8"))

    val plsBytes =
      "[playlist]\r\nFile1=C:\\Music\\Track1.mp3\r\nTitle1=Track 1\r\nNumberOfEntries=1\r\nVersion=2\r\n"
        .toByteArray(Charsets.UTF_8)
    assertEquals(DetectedWinampFormat.PlaylistPls, DroidAmpFileSniffer.sniff(plsBytes, "station.pls"))
  }

  @Test
  fun rejectsNonSkinZipEmptyAndCorruptBinaryInputs() {
    val nonSkinZip =
      buildZip(
        "docs/readme.txt" to "hello world".toByteArray(Charsets.UTF_8),
        "images/photo.jpg" to byteArrayOf(1, 2, 3, 4),
      )
    val nonSkinResult = DroidAmpFileSniffer.sniff(nonSkinZip, "archive.zip")
    assertTrue(nonSkinResult is DetectedWinampFormat.Unsupported)

    val emptyResult = DroidAmpFileSniffer.sniff(ByteArray(0), "empty.wsz")
    assertTrue(emptyResult is DetectedWinampFormat.Unsupported)

    val corruptBinary = byteArrayOf(0x7F, 0x45, 0x4C, 0x46, 0x00, 0x01, 0x02, 0x03)
    val binaryResult = DroidAmpFileSniffer.sniff(corruptBinary, "mystery.wsz")
    assertTrue(binaryResult is DetectedWinampFormat.Unsupported)

    val truncatedEqf = WinampEqBinaryContainer.HEADER_BYTES + byteArrayOf(1, 2, 3, 4, 5)
    val truncatedResult = DroidAmpFileSniffer.sniff(truncatedEqf, "broken.eqf")
    assertTrue(truncatedResult is DetectedWinampFormat.Unsupported)
  }

  private fun buildZip(vararg entries: Pair<String, ByteArray>): ByteArray {
    val out = ByteArrayOutputStream()
    ZipOutputStream(out).use { zos ->
      for ((name, data) in entries) {
        zos.putNextEntry(ZipEntry(name))
        zos.write(data)
        zos.closeEntry()
      }
    }
    return out.toByteArray()
  }
}
